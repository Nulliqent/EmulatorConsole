import fs from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import zlib from "node:zlib";
import type { ModelIndexMeta, OperationInfo, ServiceSummary } from "../../shared/models.js";
import { reachableShapes } from "./sensitive.js";
import { INDEX_FILE, SCHEMA_VERSION, SERVICES_DIR, serviceFileName } from "./types.js";
import type { ModelIndexFile, ServiceModelFile, SmithyShape } from "./types.js";

export type { ModelIndexFile, ServiceModelFile, SmithyShape } from "./types.js";
export * from "./sensitive.js";

const brotliDecompress = promisify(zlib.brotliDecompress);

/** Decompressed bytes of service shape graphs kept in memory. The summaries of all services always are. */
export const DEFAULT_CACHE_BYTES = 100 * 1024 * 1024;

type Cached = { pending: Promise<ServiceModelFile>; bytes: number };

/**
 * The Service Model index generated by `npm run model-index`: a summary of every service, held in memory, and each
 * service's operations and Smithy shape graph, read from disk the first time it is asked for. Loaded services are
 * kept until their decompressed size passes a cap; the least recently used go first.
 */
export class ModelIndex {
  readonly meta: ModelIndexMeta;
  /** Identifies this build of the index, for HTTP validators. */
  readonly version: string;
  private readonly summaries: ServiceSummary[];
  private readonly byKey = new Map<string, ServiceSummary>();
  private readonly cache = new Map<string, Cached>();
  private cachedBytes = 0;

  private constructor(private readonly dir: string, file: ModelIndexFile, private readonly maxCacheBytes: number) {
    this.meta = file.meta;
    this.version = `${file.meta.schemaVersion}-${file.meta.models.commit.slice(0, 12)}-${file.meta.emulator.commit.slice(0, 12)}`;
    this.summaries = file.services;
    for (const s of file.services) this.byKey.set(s.sdkId, s);
    // A slug never shadows an SDK ID.
    for (const s of file.services) if (!this.byKey.has(s.slug)) this.byKey.set(s.slug, s);
  }

  static async load(dir: string, opts: { maxCacheBytes?: number } = {}): Promise<ModelIndex> {
    const file = JSON.parse(await fs.readFile(path.join(dir, INDEX_FILE), "utf8")) as ModelIndexFile;
    if (file.meta.schemaVersion !== SCHEMA_VERSION) {
      throw new Error(`model index in ${dir} has schema ${file.meta.schemaVersion}; this build reads ${SCHEMA_VERSION}. Run npm run model-index.`);
    }
    return new ModelIndex(dir, file, opts.maxCacheBytes ?? DEFAULT_CACHE_BYTES);
  }

  /** Every service the Emulator offers, sorted by SDK ID. */
  services(): ServiceSummary[] {
    return this.summaries;
  }

  /** A service by SDK ID ("Secrets Manager") or slug ("secrets-manager"). */
  service(key: string): ServiceSummary | undefined {
    return this.byKey.get(key);
  }

  /** The services whose shape graphs are in memory, oldest first, and their decompressed size. For tests and diagnostics. */
  cacheStats(): { services: string[]; bytes: number } {
    return { services: [...this.cache.keys()], bytes: this.cachedBytes };
  }

  /** A service's operations and shape graph. `undefined` for an unknown key. */
  async detail(key: string): Promise<ServiceModelFile | undefined> {
    const summary = this.byKey.get(key);
    if (!summary) return undefined;
    const hit = this.cache.get(summary.sdkId);
    if (hit) {
      // Keep the most recently used last.
      this.cache.delete(summary.sdkId);
      this.cache.set(summary.sdkId, hit);
      return hit.pending;
    }
    const entry: Cached = { pending: this.read(summary), bytes: 0 };
    this.cache.set(summary.sdkId, entry);
    let file: ServiceModelFile;
    try {
      file = await entry.pending;
    } catch (e) {
      if (this.cache.get(summary.sdkId) === entry) this.cache.delete(summary.sdkId);
      throw e;
    }
    if (this.cache.get(summary.sdkId) === entry) {
      this.cachedBytes += entry.bytes;
      this.evict(summary.sdkId);
    }
    return file;
  }

  async operation(key: string, name: string): Promise<OperationInfo | undefined> {
    return (await this.detail(key))?.operations.find((o) => o.name === name);
  }

  /** One shape. Own properties only: `__proto__` or `constructor` is not a shape. */
  async shape(key: string, shapeId: string): Promise<SmithyShape | undefined> {
    const shapes = (await this.detail(key))?.shapes;
    return shapes && Object.hasOwn(shapes, shapeId) ? shapes[shapeId] : undefined;
  }

  /** The shapes reachable from one operation (input, output, declared errors), or `undefined` if there is no such operation. */
  async operationShapes(key: string, operation: string): Promise<Record<string, SmithyShape> | undefined> {
    const detail = await this.detail(key);
    const op = detail?.operations.find((o) => o.name === operation);
    if (!detail || !op) return undefined;
    return reachableShapes(detail.shapes, [op.shapeId, ...detail.commonErrors]);
  }

  private evict(keep: string) {
    // The one just loaded stays even if it alone passes the cap.
    for (const [k, v] of this.cache) {
      if (this.cachedBytes <= this.maxCacheBytes) break;
      if (k === keep) continue;
      this.cache.delete(k);
      this.cachedBytes -= v.bytes;
    }
  }

  private async read(summary: ServiceSummary): Promise<ServiceModelFile> {
    const packed = await fs.readFile(path.join(this.dir, SERVICES_DIR, serviceFileName(summary.slug)));
    const text = await brotliDecompress(packed);
    const entry = this.cache.get(summary.sdkId);
    if (entry) entry.bytes = text.length;
    return JSON.parse(text.toString("utf8")) as ServiceModelFile;
  }
}

const loaded = new Map<string, Promise<ModelIndex>>();

/** The index in `dir`, loaded once per process. A failed load is not remembered, so it can be retried. */
export function modelIndex(dir: string): Promise<ModelIndex> {
  let p = loaded.get(dir);
  if (!p) {
    p = ModelIndex.load(dir);
    loaded.set(dir, p);
    p.catch(() => loaded.delete(dir));
  }
  return p;
}
